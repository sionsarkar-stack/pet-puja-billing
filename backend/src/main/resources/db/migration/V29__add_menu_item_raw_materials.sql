CREATE TABLE menu_item_raw_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL REFERENCES menu_item(id) ON DELETE CASCADE,
    raw_material VARCHAR(120) NOT NULL,
    quantity VARCHAR(80) NOT NULL,
    position INTEGER NOT NULL
);

CREATE INDEX menu_item_raw_material_menu_item_idx ON menu_item_raw_material(menu_item_id);