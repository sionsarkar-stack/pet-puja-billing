CREATE TABLE daily_closing_individual_total (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_closing_id BIGINT NOT NULL REFERENCES daily_closing(id) ON DELETE CASCADE,
    source VARCHAR(80) NOT NULL,
    position INTEGER NOT NULL,
    income NUMERIC(12,2) NOT NULL,
    refunds NUMERIC(12,2) NOT NULL,
    expenses NUMERIC(12,2) NOT NULL,
    difference NUMERIC(12,2) NOT NULL,
    CONSTRAINT daily_closing_individual_total_source_unique UNIQUE (daily_closing_id, source)
);

CREATE INDEX daily_closing_individual_total_position_idx
    ON daily_closing_individual_total(daily_closing_id, position);